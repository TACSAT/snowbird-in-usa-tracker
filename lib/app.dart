// FR: Widget racine — configure MaterialApp avec le thème, les délégués de
//     localisation et la route initiale. Toutes les destinations de navigation sont
//     déclarées ici pour qu'il y ait un endroit unique pour voir quels écrans
//     existent et comment y accéder.
//
//     Note de confidentialité : debugShowCheckedModeBanner est explicitement mis à
//     false en mode release. Aucun SDK d'analyse, de rapport de plantage ou
//     dépendant du réseau n'est initialisé ici — l'appli n'a pas la permission
//     INTERNET et n'effectue aucune connexion sortante (les liens externes sont
//     ouverts par le navigateur du système, pas dans l'appli).

import 'package:flutter/material.dart';
import 'package:flutter_localizations/flutter_localizations.dart';
import 'package:provider/provider.dart';

import 'package:snowbird_in_usa_tracker/state/settings_controller.dart';

// EN: AppLocalizations is generated by `flutter gen-l10n` (or automatically by
//     the build system when `generate: true` is set in pubspec.yaml). If this
//     import is red in your IDE, run `flutter pub get && flutter gen-l10n` once.
// FR: AppLocalizations est généré par `flutter gen-l10n` (ou automatiquement par
//     le système de build quand `generate: true` est défini dans pubspec.yaml).
//     Si cet import est rouge dans votre IDE, exécuter
//     `flutter pub get && flutter gen-l10n` une fois.
import 'package:snowbird_in_usa_tracker/l10n/app_localizations.dart';

import 'package:snowbird_in_usa_tracker/screens/trip_list_screen.dart';

class SnowBirdApp extends StatelessWidget {
  const SnowBirdApp({super.key});

  @override
  Widget build(BuildContext context) {
    // EN: Watch the user's preferences so a change to language, theme, or text
    //     size rebuilds the whole app immediately.
    // FR: Observer les préférences de l'utilisateur pour qu'un changement de
    //     langue, de thème ou de taille de texte reconstruise toute l'appli
    //     immédiatement.
    final settings = context.watch<SettingsController>();

    return MaterialApp(
      // EN: App name shown in the OS task-switcher. Keep this consistent with
      //     the name submitted to the App Store and Google Play.
      // FR: Nom de l'appli affiché dans le sélecteur de tâches. Le garder
      //     cohérent avec le nom soumis à l'App Store et Google Play.
      title: 'SnowBird',
      debugShowCheckedModeBanner: false,

      // EN: Wire up the generated AppLocalizations delegate plus the Flutter
      //     framework delegates that translate built-in widgets (date pickers,
      //     accessibility labels, etc.) into the user's locale.
      // FR: Connecter le délégué AppLocalizations généré ainsi que les délégués
      //     du framework Flutter qui traduisent les widgets intégrés (sélecteurs
      //     de date, étiquettes d'accessibilité, etc.) dans la locale de
      //     l'utilisateur.
      localizationsDelegates: const [
        AppLocalizations.delegate,
        GlobalMaterialLocalizations.delegate,
        GlobalWidgetsLocalizations.delegate,
        GlobalCupertinoLocalizations.delegate,
      ],
      supportedLocales: AppLocalizations.supportedLocales,

      // EN: null locale = follow the phone's language; a non-null value is the
      //     user's explicit in-app override (FR-20).
      // FR: locale null = suivre la langue du téléphone ; une valeur non nulle est
      //     l'outrepassement explicite de l'utilisateur dans l'appli (FR-20).
      locale: settings.locale,

      theme: _theme(Brightness.light),
      darkTheme: _theme(Brightness.dark),
      themeMode: settings.themeMode,

      // EN: Apply the in-app text-scale multiplier ON TOP of the OS text size, so a
      //     user who wants everything bigger in THIS app can have it without
      //     changing their phone-wide setting (FR-20 / NFR-5). We compose with the
      //     inherited scaler rather than replacing it, so the OS accessibility
      //     setting still counts.
      // FR: Appliquer le multiplicateur d'échelle DANS l'appli PAR-DESSUS la taille
      //     de l'OS, pour qu'un utilisateur qui veut tout plus grand dans CETTE
      //     appli l'obtienne sans changer son réglage global (FR-20 / NFR-5). On
      //     compose avec l'échelle héritée plutôt que de la remplacer, pour que le
      //     réglage d'accessibilité de l'OS compte toujours.
      builder: (context, child) {
        final media = MediaQuery.of(context);
        // EN: Effective OS scale factor (1.0 base) × the user's in-app multiplier.
        //     scale(1.0) reads the current factor from whatever scaler the OS
        //     supplied, so the OS accessibility size still contributes.
        // FR: Facteur d'échelle effectif de l'OS (base 1,0) × le multiplicateur de
        //     l'utilisateur dans l'appli. scale(1.0) lit le facteur courant de
        //     l'échelle fournie par l'OS, pour que la taille d'accessibilité de
        //     l'OS compte toujours.
        final osFactor = media.textScaler.scale(1);
        return MediaQuery(
          data: media.copyWith(
            textScaler: TextScaler.linear(osFactor * settings.textScale),
          ),
          child: child ?? const SizedBox.shrink(),
        );
      },

      home: const TripListScreen(),
    );
  }

  // EN: Material 3 theme for the given brightness, built from a seed colour. A
  //     seed-based palette keeps the full colour scheme accessible (contrast ratios
  //     checked by the framework) in both light and dark without manually
  //     specifying every token. The deep-blue seed is deliberately neutral — no
  //     "danger" or "limit" connotation, consistent with the no-verdicts positioning.
  // FR: Thème Material 3 pour la luminosité donnée, construit à partir d'une couleur
  //     graine. Une palette à base de graine maintient le schéma accessible (ratios
  //     de contraste vérifiés par le framework) en clair comme en sombre sans
  //     spécifier chaque jeton. La graine bleu foncé est volontairement neutre —
  //     aucune connotation de « danger » ou de « limite », cohérente avec le
  //     positionnement sans verdict.
  ThemeData _theme(Brightness brightness) {
    return ThemeData(
      useMaterial3: true,
      brightness: brightness,
      colorScheme: ColorScheme.fromSeed(
        // EN: Deep blue — calm, professional, universally readable.
        // FR: Bleu foncé — calme, professionnel, universellement lisible.
        seedColor: const Color(0xFF1565C0),
        brightness: brightness,
      ),
    );
  }
}
